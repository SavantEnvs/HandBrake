#define HB_PROJECT_SECURITY_HARDEN 0
#endif
EOF_H

PKGS="libass freetype2 jansson x264 libbluray dvdread dvdnav fribidi"
PKG_CFLAGS="$(pkg-config --cflags $PKGS)"
FF_LIBS="$(pkg-config --static --libs libavformat libavfilter libavcodec libswscale libswresample libavutil)"
LIBS="$FF_LIBS $(pkg-config --static --libs $PKGS) \
  -lx265 -lvorbis -lvorbisenc -ltheoraenc -ltheoradec -logg -lturbojpeg -lopus -lmp3lame -lspeex \
  -lharfbuzz -lbz2 -lz -llzma -lpthread -lm -ldl -lstdc++"

DEFS="-DSYS_LINUX -D_LARGEFILE_SOURCE -D_FILE_OFFSET_BITS=64 -D__LIBHB__"
HB_INCS="-I$INC -Ilibhb -I$FFMPEG_PREFIX/include $PKG_CFLAGS"

# Sources: all of libhb/*.c except the two encoders that need x265/SVT-AV1 4.3 (stubbed instead).
SRCS="$(ls libhb/*.c | grep -v -e '/encx265\.c$' -e '/encsvtav1\.c$')"


export DEFS HB_INCS
# compile_lib <objdir> <libfile> <compiler flags...>
compile_lib() {
    local objdir=$1 lib=$2; shift 2
    mkdir -p "$objdir"
    rm -f "$lib" "$objdir"/*.o
    export OBJDIR=$objdir CMD="$CC -w $* $DEFS $HB_INCS"
    printf '%s\n' $SRCS mayhem/encoder_stubs.c |
        xargs -P "$MAYHEM_JOBS" -n1 sh -c 'exec $CMD -c "$1" -o "$OBJDIR/$(basename "$1" .c).o"' _
    ar rcs "$lib" "$objdir"/*.o
}

# 1) Sanitized + instrumented libhb. -fsanitize=fuzzer-no-link adds SanCov edge coverage to the library.
# shellcheck disable=SC2086
compile_lib "$HB/obj-san" "$HB/libhb-san.a" -O1 $SANITIZER_FLAGS $DEBUG_FLAGS -fsanitize=fuzzer-no-link

# 2) Harnesses: fuzzer binary + -standalone reproducer each, LSan disabled at build time.
$CXX $SANITIZER_FLAGS -c mayhem/lsan_off.cc -o "$HB/lsan_off.o"
$CC $SANITIZER_FLAGS $DEBUG_FLAGS -c "$STANDALONE_FUZZ_MAIN" -o "$HB/standalone_main.o"
for t in fuzz_presets fuzz_filter_settings fuzz_stream fuzz_subtitle_style fuzz_nal; do
    # shellcheck disable=SC2086
    $CC -O1 $SANITIZER_FLAGS $DEBUG_FLAGS $DEFS $HB_INCS -c "mayhem/$t.c" -o "$HB/$t.o"
    # shellcheck disable=SC2086
    $CC $SANITIZER_FLAGS $DEBUG_FLAGS $LIB_FUZZING_ENGINE "$HB/$t.o" "$HB/libhb-san.a" "$HB/lsan_off.o" \
        $LIBS -o "$SRC/$t"
    # shellcheck disable=SC2086
    $CC $SANITIZER_FLAGS $DEBUG_FLAGS "$HB/standalone_main.o" "$HB/$t.o" "$HB/libhb-san.a" "$HB/lsan_off.o" \
        $LIBS -o "$SRC/$t-standalone"
done

# 3) Test oracle binaries with the project's NORMAL flags (no sanitizers): upstream's CLI and a
#    known-answer probe over libhb.
# shellcheck disable=SC2086
compile_lib "$HB/obj-plain" "$HB/libhb-plain.a" -O2 $COVERAGE_FLAGS
# shellcheck disable=SC2086
$CC -O2 $COVERAGE_FLAGS $DEFS $HB_INCS -Itest test/test.c test/parsecsv.c "$HB/libhb-plain.a" $LIBS \
    -o "$SRC/HandBrakeCLI"
# shellcheck disable=SC2086
$CC -O2 $COVERAGE_FLAGS $DEFS $HB_INCS mayhem/kat.c "$HB/libhb-plain.a" $LIBS -o "$SRC/hb_kat"
