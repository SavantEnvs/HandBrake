#!/usr/bin/env bash
#
# mayhem/build.sh — builds libhb (sanitized + normal), the four fuzz harnesses (+ -standalone
# reproducers), and the normal-flags HandBrakeCLI / hb_kat binaries that mayhem/test.sh runs.
# Runs inside the commit image as `mayhem` in /mayhem, offline: every dependency is an apt -dev package
# or the FFmpeg prefix in /opt/toolchains/deps (see mayhem/Dockerfile).
set -euo pipefail

# clang rejects SOURCE_DATE_EPOCH='' (empty) — it must be unset or a valid integer.
[ -n "${SOURCE_DATE_EPOCH:-}" ] || unset SOURCE_DATE_EPOCH

# Build knobs come from the ENVIRONMENT (overridable), with sane defaults — no if-statements,
# just parameter-expansion fallbacks. Default sanitizers are the base's ASan+UBSan (halting); override
# per build via the Dockerfile's `--build-arg SANITIZER_FLAGS="..."`.
# NB: SANITIZER_FLAGS uses `=` (no colon) on purpose — `=` only fills when the var is UNSET, so an
# explicit EMPTY value (`--build-arg SANITIZER_FLAGS=`) is honored and builds with NO sanitizers
# (useful when you want the program's natural crash / full backtrace, not an ASan report). The other
# knobs use `:=` (default on empty too). MAYHEM_JOBS sets build parallelism (falls back to nproc).
: "${SANITIZER_FLAGS=-fsanitize=address,undefined -fno-sanitize-recover=all -fno-omit-frame-pointer}"
# DEBUG_FLAGS carries DWARF debug info INDEPENDENTLY of the sanitizer off-switch (so an empty
# SANITIZER_FLAGS still yields DWARF symbols). DWARF MUST be < 4 (Mayhem triage can't read >=4); clang-19's
# plain `-g` emits DWARF-5, so `-gdwarf-3` is explicit. Apply $DEBUG_FLAGS to the fuzz/harness/standalone
# builds (NOT the test/oracle build). Rust/Go carry the same intent via their language flags below.
: "${DEBUG_FLAGS:=-g -gdwarf-3}"
: "${RUST_DEBUG_FLAGS:=-C debuginfo=2 -C force-frame-pointers=yes -C llvm-args=-gdwarf-3}"
: "${GO_DEBUG_FLAGS:=-gcflags=all=-N -l}"
: "${CC:=clang}" ; : "${CXX:=clang++}" ; : "${LIB_FUZZING_ENGINE:=-fsanitize=fuzzer}"
: "${MAYHEM_JOBS:=$(nproc)}"
# COVERAGE_FLAGS: empty by default → no effect on the normal oracle build. Set it via the Dockerfile's
# `--build-arg COVERAGE_FLAGS="-fprofile-instr-generate -fcoverage-mapping"` to instrument the TEST
# build for source-coverage measurement (how much of the project the test suite actually exercises —
# a quality signal for the oracle; complements the anti-reward-hack sabotage check). APPEND it to the
# test build's compile+link flags in step 3 (NOT the fuzz build); after `test.sh` runs, merge with
# `llvm-profdata` and report with `llvm-cov`. Empty value is honored (`=`, not `:=`).
: "${COVERAGE_FLAGS=}"
export SANITIZER_FLAGS DEBUG_FLAGS RUST_DEBUG_FLAGS GO_DEBUG_FLAGS CC CXX LIB_FUZZING_ENGINE MAYHEM_JOBS COVERAGE_FLAGS

cd "$SRC"

# HandBrake's own build (./configure + make) fetches and builds ~40 contrib tarballs. libhb is instead
# compiled here directly from libhb/*.c against distro -dev packages plus the FFmpeg 9.0.2 static prefix
# the Dockerfile pre-builds under /opt/toolchains/deps (SPEC §6.2 item 19). Everything below is offline.
FFMPEG_PREFIX=/opt/toolchains/deps/ffmpeg-9.0.2
export PKG_CONFIG_PATH="$FFMPEG_PREFIX/lib/pkgconfig${PKG_CONFIG_PATH:+:$PKG_CONFIG_PATH}"

HB=build/hb
INC="$HB/inc"
mkdir -p "$INC/handbrake"

# project.h is normally generated by ./configure from project.h.m4; this is the Linux CLI feature set
# (no GTK, no hardware encoders; x265/SVT-AV1 are stubbed, see mayhem/encoder_stubs.c).
cat > "$INC/handbrake/project.h" <<'EOF_H'
#ifndef HB_PROJECT_H
#define HB_PROJECT_H
#define HB_PROJECT_TITLE "HandBrake mayhem"
#define HB_PROJECT_NAME "HandBrake"
#define HB_PROJECT_NAME_LOWER "handbrake"
#define HB_PROJECT_NAME_UPPER "HANDBRAKE"
#define HB_PROJECT_URL_WEBSITE "https://handbrake.fr/"
#define HB_PROJECT_URL_COMMUNITY "https://forum.handbrake.fr/"
#define HB_PROJECT_URL_IRC "irc.freenode.net/handbrake"
#define HB_PROJECT_URL_APPCAST ""
#define HB_PROJECT_VERSION_MAJOR 1
#define HB_PROJECT_VERSION_MINOR 11
#define HB_PROJECT_VERSION_POINT 0
#define HB_PROJECT_VERSION "1.11.0"
#define HB_PROJECT_VERSION_HEX 0x000001000b000000LL
#define HB_PROJECT_BUILD 2026010100
